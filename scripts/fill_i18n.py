KEY_RE = re.compile(r'<string name="([^"]+)"')


def keys_in(path: Path) -> set[str]:
    return set(KEY_RE.findall(path.read_text(encoding="utf-8")))


def escape(text: str) -> str:
    return text.replace("&", "&amp;").replace("<", "&lt;").replace(">", "&gt;")


def main() -> None:
    src_keys = keys_in(SRC)
    for locale, table in TRANSLATIONS.items():
        dest = ROOT / f"values-{locale}" / "strings.xml"
        if not dest.exists():
            print("missing", dest)
            continue
        existing = keys_in(dest)
        missing = [k for k in table if k in src_keys and k not in existing]
        if not missing:
            print(locale, "ok")
            continue
        text = dest.read_text(encoding="utf-8")
        insert = "".join(f'    <string name="{k}">{escape(table[k])}</string>\n' for k in missing)
        if "</resources>" not in text:
            raise SystemExit(f"no resources end in {dest}")
        dest.write_text(text.replace("</resources>", insert + "</resources>", 1), encoding="utf-8")
        print(locale, "added", len(missing))


if __name__ == "__main__":
    main()
